/**
 * Fork mode — a new business, built from the logistics system as a template.
 *
 * The extend pipeline (spec → gap → plan) answers "what must change in THIS system?".
 * Fork mode answers a different question: "what does the same system look like for a
 * dental clinic?" The answer is mostly already written. The kernel (commitments, the
 * twin, the policy gate, the ledger, the sentinel, memory) is generic; the CRM tables,
 * the voice agents and the n8n workflows are freight-shaped copies of generic parts. So
 * the model is not asked to design a system. It is asked for the *delta*: which states,
 * which actions, which columns to rename, drop or add, which agents and workflows to keep.
 *
 * That framing is where the token saving comes from, and it is large:
 *
 *   - one model call per request, over a compact digest of the template (a few thousand
 *     tokens) rather than its code, returning a config of a couple of thousand tokens;
 *   - everything after it — SQL, workflow JSON, agent prompts, the vertical config — is
 *     generated by plain functions in blueprint.ts, at zero tokens;
 *   - drafts are cached on disk by (request, template), so re-running a request, or
 *     restarting the builder, costs nothing.
 *
 * The digest sits in the system prompt and the request in the user turn, so the stable
 * part is the prefix a provider can cache.
 *
 * What the model returns is untrusted. It is parsed with zod, every identifier that will
 * reach SQL or a file path is held to a strict pattern, and the result is checked against
 * the template before anything is generated from it — a column that does not exist, a
 * state nothing leads to, a table name that would collide with a live one. When a check
 * fails the model gets exactly one repair attempt with the problems listed, because a
 * second full generation costs more than the repair and fixes less.
 */
