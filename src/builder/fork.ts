/** Anything that becomes a SQL identifier, a file name or a state name. */
const Ident = z.string().regex(/^[a-z][a-z0-9_]{0,39}$/, "lowercase snake_case, starting with a letter, at most 40 chars");

export const SQL_TYPES = [
  "text", "integer", "bigint", "numeric", "boolean", "date",
  "timestamp with time zone", "jsonb", "uuid", "text[]",
] as const;

const Approver = z.enum(["desk", "compliance", "finance"]);

export const ForkSpecSchema = z.object({
  vertical: z.object({
    id: Ident,
    label: z.string().min(1),
    business: z.object({
      name: z.string().min(1),
      currency: z.string().min(3).max(3),
      currencySymbol: z.string().min(1).max(4),
      locale: z.string().min(2),
      timezone: z.string().min(3),
    }),
    lifecycle: z.object({
      order: z.array(Ident).min(2).max(12),
      initial: Ident,
      states: z.record(Ident, z.object({
        label: z.string(),
        requirements: z.array(z.string()).default([]),
        actions: z.array(Ident).default([]),
        next: z.array(Ident).default([]),
      })),
    }),
    actions: z.array(Ident).min(1).max(30),
    policy: z.object({
      alwaysApprove: z.record(Ident, z.object({ why: z.string(), approver: Approver })).default({}),
      thresholds: z.array(z.object({
        actions: z.array(Ident).min(1),
        measure: z.enum(["amount", "discountPct"]),
        limit: z.number().nonnegative(),
        trigger: z.enum(["atOrAbove", "above"]),
        approver: Approver,
      })).default([]),
    }),
    vocabulary: z.array(z.string()).default([]),
    capabilityModules: z.array(z.string()).default([]),
  }),
  entities: z.array(z.object({
    /** A template table to clone, or null for a genuinely new table. */
    from: z.string().nullable(),
    to: Ident,
    purpose: z.string(),
    rename: z.record(z.string(), Ident).default({}),
    drop: z.array(z.string()).default([]),
    add: z.array(z.object({ name: Ident, type: z.enum(SQL_TYPES) })).default([]),
    /** The business's own words for this table, for the builder's later gap analysis. */
    aliases: z.array(z.string()).default([]),
  })).min(1).max(12),
  agents: z.array(z.object({
    from: z.string(),
    to: z.string().min(1).max(40),
    role: z.string(),
    /** Not asked of the model — built from the business name in normalise(). */
    greeting: z.string().default(""),
    collects: z.array(z.string()).default([]),
  })).max(4),
  workflows: z.array(z.object({
    from: z.string(),
    to: z.string().min(1).max(80),
    keep: z.boolean(),
    why: z.string(),
  })),
  memory: z.object({ dataset: Ident, domains: z.array(z.string()).default([]) }),
  openQuestions: z.array(z.object({ question: z.string(), blocks: z.enum(["structure", "behaviour"]) })).default([]),
});

export type ForkSpec = z.infer<typeof ForkSpecSchema>;

/** The fork's vertical as the kernel's config type. Aliases come from the entity mapping. */
export function toVertical(spec: ForkSpec): VerticalConfig {
  const v = spec.vertical;
  const aliases: Record<string, string> = {};
  for (const e of spec.entities) for (const a of e.aliases) aliases[a.toLowerCase()] = e.to;
  return {
    id: v.id,
    label: v.label,
    business: v.business,
    lifecycle: { order: v.lifecycle.order, initial: v.lifecycle.initial, states: v.lifecycle.states },
    actions: v.actions,
    policy: v.policy,
    builder: { vocabulary: v.vocabulary, entityAliases: aliases, capabilityModules: v.capabilityModules },
  };
}

/**
 * Everything wrong with a spec, checked against the template it claims to adapt.
 * Empty means the blueprint can be generated from it.
 */
export function checkFork(spec: ForkSpec, t: Template): string[] {
  const problems = validateVertical(toVertical(spec)).map((p) => `vertical: ${p}`);
  const liveTables = new Set(t.tables.map((x) => x.name));

  const targets = new Set<string>();
  for (const e of spec.entities) {
    if (targets.has(e.to)) problems.push(`entities: "${e.to}" is produced twice`);
    targets.add(e.to);
    // A clone may keep its template name when the table is generic (call_logs). That is
    // only safe in a new project, which BUILD.md already requires; the blueprint warns.
    if (liveTables.has(e.to) && e.from !== e.to) problems.push(`entities: "${e.to}" is the name of a different template table`);

    if (e.from === null) {
      if (!e.add.length) problems.push(`entities: new table "${e.to}" has no columns in "add"`);
      continue;
    }
    const base = t.tables.find((x) => x.name === e.from);
    if (!base) {
      problems.push(`entities: "${e.to}" clones "${e.from}", which is not a template table (${[...liveTables].join(", ")})`);
      continue;
    }
    const cols = new Set(base.columns.map((c) => c.name));
    if (t.observed.schema) {
      for (const c of Object.keys(e.rename)) if (!cols.has(c)) problems.push(`entities: "${e.to}" renames "${c}", which ${e.from} does not have`);
      for (const c of e.drop) if (!cols.has(c)) problems.push(`entities: "${e.to}" drops "${c}", which ${e.from} does not have`);
    }
    for (const pk of base.primaryKey) {
      if (e.drop.includes(pk)) problems.push(`entities: "${e.to}" drops "${pk}", the primary key of ${e.from}`);
    }
    const kept = [...cols].filter((c) => !e.drop.includes(c)).map((c) => e.rename[c] ?? c);
    for (const a of e.add) if (kept.includes(a.name)) problems.push(`entities: "${e.to}" adds "${a.name}", which it already has`);
    if (new Set(kept).size !== kept.length) problems.push(`entities: "${e.to}" renames two columns to the same name`);
  }

  const agentNames = new Set(t.agents.map((a) => a.name));
  const agentTargets = new Set<string>();
  for (const a of spec.agents) {
    if (!agentNames.has(a.from)) problems.push(`agents: "${a.to}" clones "${a.from}", which is not a template agent (${[...agentNames].join(", ")})`);
    if (agentTargets.has(a.to)) problems.push(`agents: "${a.to}" appears twice`);
    agentTargets.add(a.to);
  }

  const wfNames = new Map(t.workflows.map((w) => [norm(w.name), w.name]));
  const seen = new Set<string>();
  for (const w of spec.workflows) {
    const hit = matchWorkflow(t, w.from);
    if (!hit) problems.push(`workflows: "${w.from}" is not a template workflow (${[...wfNames.values()].join(" | ")})`);
    else if (seen.has(hit.name)) problems.push(`workflows: "${hit.name}" appears twice`);
    else seen.add(hit.name);
  }

  if (spec.memory.dataset === t.memory.dataset) {
    problems.push(`memory: "${spec.memory.dataset}" is the template's dataset — the new business needs its own`);
  }
  return problems;
}

const norm = (s: string) => s.toLowerCase().replace(/[^a-z0-9]/g, "");

/**
 * Fixes the mechanical slips a model makes, in code, before anything is judged.
 *
 * Measured on the first real dental run: the draft was right in every way that mattered
 * and failed on "adds appointment_status, which it already has" — and the paid-for repair
 * call returned the same slip. A slip whose fix is unambiguous is cheaper to fix here, at
 * zero tokens, than to explain to a model. Each fix is recorded, so the reviewer sees what
 * the builder changed on the model's behalf. Anything that needs judgement — a state
 * nothing reaches, a dropped primary key, a table that is not in the template — is left
 * for checkFork to report.
 */
export function normalise(spec: ForkSpec, t: Template, request = ""): { spec: ForkSpec; notes: string[] } {
  const s = structuredClone(spec);
  const notes: string[] = [];
  const v = s.vertical;

  // A business name the requester never said is a guess dressed as a fact — the first
  // dental run named the clinic "Chennai Smiles Dental Clinic" from a request that gave
  // no name. It stays (something has to go in the greeting) but becomes an open question.
  if (request && !request.toLowerCase().includes(v.business.name.toLowerCase())) {
    s.openQuestions.push({ question: `The business name "${v.business.name}" was not in the request — confirm it or give the real one.`, blocks: "behaviour" });
    notes.push(`business name "${v.business.name}" is the model's placeholder — added as an open question`);
  }

  // Actions: a state granting an undeclared action declares it; a declared action no
  // state grants is dropped. Either way the list ends up matching the lifecycle.
  const granted = new Set(v.lifecycle.order.flatMap((st) => v.lifecycle.states[st]?.actions ?? []));
  for (const a of granted) {
    if (!v.actions.includes(a)) {
      v.actions.push(a);
      notes.push(`declared action "${a}", which a state grants`);
    }
  }
  const unused = v.actions.filter((a) => !granted.has(a));
  if (unused.length) {
    v.actions = v.actions.filter((a) => granted.has(a));
    notes.push(`dropped action${unused.length === 1 ? "" : "s"} no state grants: ${unused.join(", ")}`);
  }
  for (const a of Object.keys(v.policy.alwaysApprove)) {
    if (!v.actions.includes(a)) {
      delete v.policy.alwaysApprove[a];
      notes.push(`dropped always-approve on "${a}", which no state grants`);
    }
  }
  v.policy.thresholds = v.policy.thresholds
    .map((r) => {
      const keep = r.actions.filter((a) => v.actions.includes(a) && !(a in v.policy.alwaysApprove));
      if (keep.length !== r.actions.length) {
        notes.push(`threshold on ${r.actions.join("/")}: kept ${keep.join("/") || "nothing"} (the rest are undeclared or always approved)`);
      }
      return { ...r, actions: keep };
    })
    .filter((r) => r.actions.length);

  // Greetings are built here, never taken from the model. The template's own agent shipped
  // with its prompt naming one company and its greeting another, so every call opened with
  // the wrong name; and drafts kept doing the same — "Smile Dental Clinic" in the greeting
  // of a business named "Dental clinic", which a substring check waves through. A greeting
  // is the one line every caller hears, and it can only say the one name.
  //
  // And an agent's name is its own (agentNames.ts): a draft that keeps "Priya", or names
  // two agents alike, gets a fresh name here — the greeting below is then built with it.
  const takenNames = new Set(t.agents.map((x) => x.name.toLowerCase()));
  for (const a of s.agents) {
    if (takenNames.has(a.to.toLowerCase())) {
      const fresh = pickName(a.from || a.to, takenNames, `${v.id}|${a.from}|${a.role}`);
      notes.push(`agent "${a.to}" is renamed ${fresh} — ${t.agents.some((x) => x.name.toLowerCase() === a.to.toLowerCase()) ? "that name answers for the template" : "another agent here already has it"}, and every app's agents are its own`);
      a.to = fresh;
    }
    takenNames.add(a.to.toLowerCase());
    const built = `${v.business.name}, this is ${a.to}. How can I help you today?`;
    if (a.greeting && a.greeting !== built) notes.push(`${a.to}'s greeting is built from the business name, not the model's ("${a.greeting.slice(0, 60)}")`);
    a.greeting = built;
  }

  // Same for a threshold figure. Measured: a dental draft set bookings at ₹5,000 from a
  // request that named no amount — plausible, and exactly the invented specific that reads
  // like a requirement by the time it reaches a policy gate.
  const digits = request.replace(/[,\s]/g, "");
  for (const r of v.policy.thresholds) {
    if (request && !digits.includes(String(r.limit))) {
      const what = r.measure === "amount" ? `${v.business.currencySymbol}${r.limit.toLocaleString(v.business.locale)}` : `${r.limit}%`;
      s.openQuestions.push({ question: `The ${what} approval threshold on ${r.actions.join("/")} was not in the request — confirm the real figure.`, blocks: "behaviour" });
      notes.push(`threshold ${what} on ${r.actions.join("/")} is assumed — added as an open question`);
    }
  }

  // Columns: renames and drops of columns the template table does not have are no-ops
  // the model wrote by mistake; an add that collides with a kept column is a duplicate.
  if (t.observed.schema) {
    for (const e of s.entities) {
      const base = e.from ? t.tables.find((x) => x.name === e.from) : undefined;
      if (!base) continue;
      const cols = new Set(base.columns.map((c) => c.name));
      // "x_m": "x_m" is not a rename. Measured: the model listed every column of a table
      // this way and ALSO dropped the freight ones, so an identity entry must not be what
      // keeps a dropped column alive.
      const identity = Object.keys(e.rename).filter((c) => e.rename[c] === c);
      for (const c of identity) delete e.rename[c];
      const revived = identity.filter((c) => e.drop.includes(c));
      if (revived.length) notes.push(`${e.to}: dropped ${revived.join(", ")} — they were "renamed" to themselves as well as dropped`);
      for (const c of Object.keys(e.rename)) {
        if (!cols.has(c)) {
          delete e.rename[c];
          notes.push(`${e.to}: ignored rename of "${c}", which ${e.from} does not have`);
        } else if (e.drop.includes(c)) {
          e.drop = e.drop.filter((x) => x !== c);
          notes.push(`${e.to}: "${c}" was both renamed and dropped — kept the rename`);
        }
      }
      const badDrops = e.drop.filter((c) => !cols.has(c));
      if (badDrops.length) {
        e.drop = e.drop.filter((c) => cols.has(c));
        notes.push(`${e.to}: ignored drop of ${badDrops.join(", ")}, not in ${e.from}`);
      }
      // Two template columns renamed to one name. A mechanical slip like the others here,
      // and until now the only one that failed the whole run: checkFork rejected it after
      // a repair call had already been spent. The first column keeps the new name and the
      // rest keep their template name, which is unique by construction \u2014 and if the
      // column was freight geometry it is flagged leftover and hidden anyway.
      const taken = new Set<string>();
      for (const c of base.columns.map((x) => x.name)) {
        if (e.drop.includes(c)) continue;
        const want = e.rename[c] ?? c;
        if (!taken.has(want)) { taken.add(want); continue; }
        delete e.rename[c];
        if (taken.has(c)) {
          e.drop.push(c);
          notes.push(`${e.to}: dropped "${c}" \u2014 it was renamed to "${want}", which another column already takes`);
        } else {
          taken.add(c);
          notes.push(`${e.to}: "${c}" keeps its name \u2014 it was renamed to "${want}", which another column already takes`);
        }
      }

      const kept = new Set([...cols].filter((c) => !e.drop.includes(c)).map((c) => e.rename[c] ?? c));
      const dupes = e.add.filter((a) => kept.has(a.name));
      if (dupes.length) {
        e.add = e.add.filter((a) => !kept.has(a.name));
        notes.push(`${e.to}: ${dupes.map((a) => a.name).join(", ")} already present — not added twice`);
      }
    }
  }
  return { spec: s, notes };
}

/** By exact name, by file, or by the "01"-style number — small models abbreviate. */
export function matchWorkflow(t: Template, ref: string): TemplateWorkflow | undefined {
  const n = norm(ref);
  return (
    t.workflows.find((w) => norm(w.name) === n) ??
    t.workflows.find((w) => norm(w.file) === n || norm(w.file.replace(/\.json$/, "")) === n) ??
    t.workflows.find((w) => {
      const num = w.file.slice(0, 2);
      return new RegExp(`(^|[^0-9])${num}([^0-9]|$)`).test(ref);
    }) ??
    // "Call to commitments" for "SHIPMATE 01 — Call to commitments".
    (n.length >= 6 ? t.workflows.find((w) => norm(w.name).includes(n)) : undefined)
  );
}

