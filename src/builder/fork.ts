// ------------------------------------------------------------------------------ template

export interface TemplateTable {
  name: string;
  note: string;
  primaryKey: string[];
  columns: Array<{ name: string; type: string }>;
}

export interface TemplateWorkflow {
  file: string;
  name: string;
  trigger: string;
  webhookPaths: string[];
  /** SHIPMATE endpoints it calls, relative to SHIPMATE_BASE. */
  calls: string[];
  /** From the live instance. Null when n8n could not be read. */
  active: boolean | null;
}

export interface TemplateAgent {
  name: string;
  role: string;
  /** From the live account. Null when SnapServe could not be read. */
  wired: boolean | null;
  knowledgeSources: number | null;
}

export interface Template {
  id: string;
  label: string;
  vertical: VerticalConfig;
  tables: TemplateTable[];
  agents: TemplateAgent[];
  workflows: TemplateWorkflow[];
  memory: { dataset: string; reachable: boolean | null };
  /** Which parts were read live. A fork drafted against an unread schema cannot clone columns. */
  observed: { schema: boolean; workflows: boolean; agents: boolean; memory: boolean };
}

/**
 * The logistics system as a template: its config, the tables worth cloning (with their
 * deployed columns), its agents and its workflows.
 *
 * Tables come from the live schema, because cloning a table means copying its columns and
 * types and the repo does not hold the deployed truth. Workflows come from this repo's
 * n8n/ files — those are what gets cloned — with the live active flag laid over them.
 */
export function readTemplate(manifest: Manifest, repoRoot: string): Template {
  const v = freight as unknown as VerticalConfig;
  const notes = v.builder.tableNotes ?? {};

  const tables: TemplateTable[] = Object.entries(notes).map(([name, note]) => {
    const e = manifest.entities.items.find((x) => x.name === name);
    return {
      name,
      note,
      primaryKey: e?.primaryKey ?? [],
      columns: (e?.fields ?? []).map((f) => ({ name: f, type: e?.types?.[f] ?? "text" })),
    };
  });

  const dir = join(repoRoot, "n8n");
  const workflows: TemplateWorkflow[] = readdirSync(dir)
    .filter((f) => f.endsWith(".json"))
    .sort()
    .map((file) => {
      const w = JSON.parse(readFileSync(join(dir, file), "utf-8")) as {
        name: string;
        nodes: Array<{ type: string; parameters?: { path?: string; url?: string } }>;
      };
      const trig = w.nodes.find((n) => /webhook$|Trigger$/.test(n.type));
      const live = manifest.workflows.observed ? manifest.workflows.items.find((x) => x.name === w.name) : undefined;
      return {
        file,
        name: w.name,
        trigger: (trig?.type ?? "manual").split(".").pop() ?? "manual",
        webhookPaths: w.nodes.filter((n) => n.type.endsWith(".webhook")).map((n) => n.parameters?.path ?? ""),
        calls: [
          ...new Set(
            w.nodes
              .map((n) => n.parameters?.url ?? "")
              .filter((u) => u.includes("SHIPMATE_BASE"))
              .map((u) => u.replace(/^=?\{\{ \$env\.SHIPMATE_BASE \}\}/, "").replace(/\{\{.*?\}\}/g, ":ref")),
          ),
        ],
        active: manifest.workflows.observed ? Boolean(live?.active) : null,
      };
    });

  const agents: TemplateAgent[] = ROUTES.map((r) => {
    const live = manifest.agents.observed ? manifest.agents.items.find((a) => a.name === r.agentName) : undefined;
    return {
      name: r.agentName,
      role: `${r.kind}: ${r.why}`,
      wired: manifest.agents.observed ? Boolean(live?.webhookUrl) : null,
      knowledgeSources: live?.knowledgeSourceCount ?? null,
    };
  });

  return {
    id: "araxys-logistics",
    label: "Araxys Logistics (freight forwarding CRM)",
    vertical: v,
    tables,
    agents,
    workflows,
    memory: {
      dataset: process.env.COGNEE_DATASET ?? "araxys_shipments",
      reachable: manifest.memory.observed ? Boolean(manifest.memory.items[0]?.reachable) : null,
    },
    observed: {
      schema: manifest.entities.observed,
      workflows: manifest.workflows.observed,
      agents: manifest.agents.observed,
      memory: manifest.memory.observed,
    },
  };
}

/**
 * The template as the model sees it. Deliberately terse — every line here is paid for on
 * every uncached request — and deterministic, so the same template always produces the
 * same bytes and the same cache key.
 */
export function digest(t: Template): string {
  const v = t.vertical;
  const states = v.lifecycle.order.join(" -> ");
  const back = v.lifecycle.order
    .flatMap((s) => v.lifecycle.states[s].next.filter((n) => v.lifecycle.order.indexOf(n) < v.lifecycle.order.indexOf(s)).map((n) => `${s}->${n}`))
    .join(", ");
  const always = Object.entries(v.policy.alwaysApprove).map(([a, r]) => `${a} (${r!.approver})`).join(", ");
  const thresholds = v.policy.thresholds
    .map((r) => `${r.actions.join("/")} ${r.measure} ${r.trigger} ${r.limit} -> ${r.approver}`)
    .join("; ");

  return [
    `TEMPLATE: ${t.label}. Business: ${v.business.name}, ${v.business.currency}, ${v.business.timezone}.`,
    "",
    "KERNEL (fixed code, reused unchanged by every business): commitments engine (promises with owner, deadline, evidence); digital twin (runs YOUR lifecycle and only allows each state's actions); policy gate (alwaysApprove actions + numeric thresholds on \"amount\" or \"discountPct\"); audit ledger; deadline sentinel (sweeps open commitments); Cognee memory.",
    "",
    `TEMPLATE LIFECYCLE (shape reference only): ${states}. Backward edges: ${back || "none"}.`,
    `TEMPLATE ACTIONS: ${v.actions.join(", ")}.`,
    `TEMPLATE POLICY: alwaysApprove ${always}. thresholds: ${thresholds}.`,
    "",
    "TABLES (name [pk] - purpose: column:type, ...):",
    ...t.tables.map((x) => `${x.name} [${x.primaryKey.join(",") || "?"}] - ${x.note}: ${x.columns.map((c) => `${c.name}:${c.type}`).join(", ") || "(columns not readable)"}`),
    "",
    "VOICE AGENTS (answer phone calls; no tools except end_call; facts come from a knowledge base; the finished call is posted to workflow 01):",
    ...t.agents.map((a) => `${a.name} - ${a.role}`),
    "",
    "WORKFLOWS (n8n):",
    ...t.workflows.map((w) => `"${w.name}" - trigger ${w.trigger}${w.webhookPaths.length ? ` ${w.webhookPaths.join(",")}` : ""} - calls ${w.calls.join(", ") || "nothing"}`),
    "",
    `MEMORY: Cognee dataset ${t.memory.dataset} (history per customer).`,
  ].join("\n");
}

